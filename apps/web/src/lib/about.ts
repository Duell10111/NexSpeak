/**
 * Facts about this build for Settings → About. The AGPL network clause requires offering the
 * source of the running version, so the commit is baked in at build time (next.config.ts).
 */

export const REPOSITORY_URL = "https://github.com/Duell10111/NexSpeak"
export const ISSUES_URL = `${REPOSITORY_URL}/issues/new/choose`
export const LICENSE_URL = `${REPOSITORY_URL}/blob/main/LICENSE`

export const APP_VERSION = process.env.NEXT_PUBLIC_APP_VERSION || "0.0.0"
export const GIT_COMMIT = process.env.NEXT_PUBLIC_GIT_COMMIT || ""

/** The source tree of exactly this build, or the repository when the commit is unknown. */
export function sourceUrl(commit: string = GIT_COMMIT): string {
  return commit ? `${REPOSITORY_URL}/tree/${commit}` : REPOSITORY_URL
}

export interface ThirdPartyLicense {
  name: string
  version: string
  license: string
  repository?: string
  text?: string
}

/** Generated by scripts/third-party-licenses.mjs; only loaded when the About tab opens. */
export async function loadThirdPartyLicenses(): Promise<ThirdPartyLicense[]> {
  const response = await fetch("/third-party-licenses.json")
  if (!response.ok) throw new Error(`Loading the license list failed: ${response.status}`)
  return (await response.json()) as ThirdPartyLicense[]
}
