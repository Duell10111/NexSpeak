import { expect, test, type Page } from '@playwright/test'
import { createRoom, getRoomMessages, getState, login, matrixApi, newPage, openRoom, registerUser } from './helpers'

async function composePoll(page: Page, question: string, options: { multiple?: boolean; hidden?: boolean; screenshotPath?: string } = {}) {
  await page.getByRole('button', { name: 'Umfrage erstellen', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('textbox', { name: 'Frage', exact: true }).fill(question)
  await dialog.getByRole('textbox', { name: 'Antwort 1', exact: true }).fill('Heute')
  await dialog.getByRole('textbox', { name: 'Antwort 2', exact: true }).fill('Morgen')
  if (options.multiple) await dialog.getByRole('checkbox', { name: 'Mehrere Antworten erlauben' }).check()
  if (options.hidden) await dialog.getByRole('checkbox', { name: 'Ergebnisse bis zum Ende verbergen' }).check()
  if (options.screenshotPath) await dialog.screenshot({ path: options.screenshotPath })
  await dialog.getByRole('button', { name: 'Umfrage erstellen' }).click()
  await expect(dialog).not.toBeVisible()
}

test('polls: live results, changed votes, moderator permissions and no relation fetches', async ({ browser }, testInfo) => {
  const alice = await registerUser('poll-alice')
  const bob = await registerUser('poll-bob')
  const roomName = `Poll ${Date.now().toString(36)}`
  const roomId = await createRoom(alice, { name: roomName, members: [bob] })
  const alicePage = await newPage(browser)
  const bobPage = await newPage(browser)
  const relationRequests: string[] = []
  for (const page of [alicePage, bobPage]) page.on('request', (request) => { if (request.url().includes('/relations/')) relationRequests.push(request.url()) })
  await login(alicePage, alice)
  await login(bobPage, bob)
  await openRoom(alicePage, roomName)
  await openRoom(bobPage, roomName)
  await composePoll(alicePage, 'Wann spielen wir?', { screenshotPath: testInfo.outputPath('poll-composer.png') })
  const alicePoll = alicePage.getByTestId('poll')
  const bobPoll = bobPage.getByTestId('poll')
  await expect(bobPoll.getByRole('heading', { name: 'Wann spielen wir?', exact: true })).toBeVisible()
  await expect(bobPoll.getByRole('button', { name: 'Umfrage beenden' })).toHaveCount(0)
  await bobPoll.getByRole('radio', { name: /^Heute/ }).check()
  await bobPoll.getByRole('button', { name: 'Abstimmen', exact: true }).click()
  await expect(alicePoll.getByText('1 teilnehmende Person')).toBeVisible()
  await expect(alicePoll.getByRole('radio', { name: /^Heute 1 Stimme/ })).toBeVisible()
  await bobPoll.getByRole('radio', { name: /^Morgen/ }).check()
  await bobPoll.getByRole('button', { name: 'Stimme ändern' }).click()
  await expect(alicePoll.getByRole('radio', { name: /^Heute 0 Stimmen/ })).toBeVisible()
  await expect(alicePoll.getByRole('radio', { name: /^Morgen 1 Stimme/ })).toBeVisible()
  await expect(alicePoll.getByText('1 teilnehmende Person')).toBeVisible()

  // Permissions update live without requiring another message to arrive.
  const levels = await getState<{ users?: Record<string, number> }>(alice, roomId, 'm.room.power_levels')
  // Room v12 assigns creator powers implicitly and forbids listing that user explicitly.
  await matrixApi(alice, 'PUT', `/rooms/${encodeURIComponent(roomId)}/state/m.room.power_levels/`, { ...levels, users: { ...levels?.users, [bob.userId]: 50 }, redact: 50 })
  await bobPoll.getByRole('button', { name: 'Umfrage beenden' }).click()
  await expect(alicePoll.getByText('Umfrage beendet', { exact: true })).toBeVisible()
  await expect(bobPoll.getByRole('radio').first()).toBeDisabled()
  await expect(alicePage.locator('[id^="msg-"]')).toHaveCount(1)
  await alicePoll.screenshot({ path: testInfo.outputPath('poll-ended-results.png') })
  expect(relationRequests).toEqual([])
  const events = await getRoomMessages(alice, roomId)
  expect(events.some((event) => event.type.includes('poll.start'))).toBe(true)
  expect(events.some((event) => event.type.includes('poll.response'))).toBe(true)
  expect(events.some((event) => event.type.includes('poll.end'))).toBe(true)
  await alicePage.context().close()
  await bobPage.context().close()
})

test('encrypted polls: multiple choices and hidden results revealed by the creator', async ({ browser }, testInfo) => {
  const alice = await registerUser('secret-poll-alice')
  const bob = await registerUser('secret-poll-bob')
  const roomName = `Secret poll ${Date.now().toString(36)}`
  const roomId = await createRoom(alice, { name: roomName, members: [bob], encrypted: true })
  const alicePage = await newPage(browser)
  const bobPage = await newPage(browser)
  await login(alicePage, alice)
  await login(bobPage, bob)
  await openRoom(alicePage, roomName)
  await openRoom(bobPage, roomName)
  await composePoll(alicePage, 'Wann könnt ihr?', { multiple: true, hidden: true, screenshotPath: testInfo.outputPath('poll-encrypted-composer.png') })
  const alicePoll = alicePage.getByTestId('poll')
  const bobPoll = bobPage.getByTestId('poll')
  await expect(bobPoll.getByRole('heading', { name: 'Wann könnt ihr?', exact: true })).toBeVisible()
  await bobPoll.getByRole('checkbox', { name: 'Heute', exact: true }).check()
  await bobPoll.getByRole('checkbox', { name: 'Morgen', exact: true }).check()
  await bobPoll.getByRole('button', { name: 'Abstimmen', exact: true }).click()
  await expect(bobPoll.getByRole('button', { name: 'Stimme ändern' })).toBeDisabled()
  await expect(alicePoll.getByText('Ergebnisse werden nach Ende der Umfrage angezeigt.')).toBeVisible()
  await expect(alicePoll.getByText(/Stimmen$/)).toHaveCount(0)
  await bobPoll.screenshot({ path: testInfo.outputPath('poll-encrypted-hidden.png') })
  await alicePoll.getByRole('button', { name: 'Umfrage beenden' }).click()
  await expect(bobPoll.getByText('Umfrage beendet', { exact: true })).toBeVisible()
  await expect(bobPoll.getByText('1 Stimme', { exact: true })).toHaveCount(2)
  await expect(bobPoll.getByText('1 teilnehmende Person')).toBeVisible()
  await expect(bobPage.locator('[id^="msg-"]')).toHaveCount(1)
  await bobPoll.screenshot({ path: testInfo.outputPath('poll-encrypted-ended.png') })
  const events = await getRoomMessages(alice, roomId)
  expect(events.filter((event) => event.type === 'm.room.encrypted')).toHaveLength(3)
  expect(events.some((event) => event.type.includes('poll.'))).toBe(false)
  await alicePage.context().close()
  await bobPage.context().close()
})
